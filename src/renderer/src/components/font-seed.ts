/**
 * Build the starter font. Fresh object every call (the model is immutable, but
 * the panel owns its own copy so "Reset to starter font" is a plain re-call).
 */
export function seedFont(name = 'myfont'): BitmapFont {
  const base = createFont({
    name,
    width: SEED_WIDTH,
    height: SEED_HEIGHT,
    baseline: SEED_BASELINE,
    monospaced: true,
    codes: SEED_ART.map((_, i) => SEED_FIRST_CODE + i)
  })
  const glyphs: Glyph[] = base.glyphs.map((g) => {
    const art = SEED_ART[g.code - SEED_FIRST_CODE]
    return art
      ? { ...g, rows: parseGlyphArt(art.split('/'), SEED_WIDTH, SEED_HEIGHT) }
      : g
  })
  return { ...base, glyphs }
}
